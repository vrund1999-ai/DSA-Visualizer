// @ts-check
/*
 * Generates src/leetcode/data/bloomberg.generated.ts from the committed
 * Bloomberg CSV (data/Bloomberg-All.csv), sourced from
 * liquidslr/leetcode-company-wise-problems.
 *
 * Run: node scripts/import-bloomberg.mjs   (or: npm run import:bloomberg)
 *
 * Output is deterministic (sorted by slug, deduped) so re-running on the same
 * CSV produces byte-identical output.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const CSV_PATH = resolve(ROOT, "data/Bloomberg-All.csv");
const OUT_PATH = resolve(ROOT, "src/leetcode/data/bloomberg.generated.ts");

/** Minimal RFC-4180 CSV parser (handles quoted fields, commas, "" escapes, CRLF). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c === "\r") {
      // ignore; \n handles the row break
    } else {
      field += c;
    }
  }
  // trailing field/row (no final newline)
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

/** EASY/MEDIUM/HARD -> easy/medium/hard */
function normalizeDifficulty(raw) {
  const d = String(raw).trim().toLowerCase();
  if (d === "easy" || d === "medium" || d === "hard") return d;
  throw new Error(`Unknown difficulty: ${raw}`);
}

/** ".../problems/<slug>" or ".../problems/<slug>/" -> "<slug>" */
function slugFromLink(link) {
  const m = String(link)
    .trim()
    .match(/problems\/([^/?#]+)/);
  if (!m) throw new Error(`Cannot derive slug from link: ${link}`);
  return m[1];
}

function splitTopics(raw) {
  return String(raw)
    .split(",")
    .map((t) => t.trim())
    .filter(Boolean);
}

function main() {
  const csv = readFileSync(CSV_PATH, "utf8");
  const rows = parseCsv(csv);
  if (rows.length === 0) throw new Error("Empty CSV");

  const header = rows[0].map((h) => h.trim());
  const col = (name) => {
    const idx = header.indexOf(name);
    if (idx === -1) throw new Error(`Missing column: ${name}`);
    return idx;
  };
  const iDifficulty = col("Difficulty");
  const iTitle = col("Title");
  const iFrequency = col("Frequency");
  const iLink = col("Link");
  const iTopics = col("Topics");

  const bySlug = new Map();
  for (let r = 1; r < rows.length; r++) {
    const row = rows[r];
    if (!row || row.length < header.length) continue;
    const title = row[iTitle].trim();
    if (!title) continue;
    const url = row[iLink].trim();
    const id = slugFromLink(url);
    const freq = Number.parseFloat(row[iFrequency]);
    const entry = {
      id,
      title,
      difficulty: normalizeDifficulty(row[iDifficulty]),
      url,
      topics: splitTopics(row[iTopics]),
      frequency: Number.isFinite(freq) ? Math.round(freq * 10) / 10 : undefined,
      companies: ["Bloomberg"],
    };
    // Keep the highest-frequency instance if a slug appears twice.
    const prev = bySlug.get(id);
    if (!prev || (entry.frequency ?? 0) > (prev.frequency ?? 0)) {
      bySlug.set(id, entry);
    }
  }

  const entries = [...bySlug.values()].sort((a, b) => a.id.localeCompare(b.id));

  const banner =
    "// AUTO-GENERATED by scripts/import-bloomberg.mjs — DO NOT EDIT BY HAND.\n" +
    "// Source: liquidslr/leetcode-company-wise-problems (Bloomberg, all-time).\n" +
    "// Regenerate: npm run import:bloomberg\n";

  const body =
    banner +
    'import type { BulkProblemMeta } from "../bulkProblems";\n\n' +
    `export const bloombergProblems: BulkProblemMeta[] = ${JSON.stringify(
      entries,
      null,
      2,
    )};\n`;

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, body, "utf8");
  console.log(`Wrote ${entries.length} problems to ${OUT_PATH}`);
}

main();
